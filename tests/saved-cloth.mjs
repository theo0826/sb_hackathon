import assert from 'node:assert/strict';
import { loadTS } from './helpers/load-ts.mjs';
const { isClothScene, snapshotClothDesign, savedClothDesign, setClothScene, getClothScene } = await loadTS('lib/cloth-scene-session.ts');
const image = 'data:image/png;base64,AAAA';
const data = {completed:1,front:image,back:image,category:{id:'tee',label:'반팔'},text:'navy tee',updatedAt:'2026-10-29T00:00:00.000Z',tokens:{color:'navy'},logo:{panel:'front',x:1,y:2,width:9,rotation:12},price:{min:10000,max:15000,label:'1~1.5만원',probability:1}};
const scene = {meta:{arrays:{X:{type:'f32',offset:0,count:3}},meshes:[{name:'front'}]},bin:new Float32Array([1,2,3]).buffer};
assert(isClothScene(scene));
assert(!isClothScene({...scene,bin:{}}));
assert(!isClothScene({...scene,meta:{...scene.meta,arrays:{X:{type:'f32',offset:0,count:4}}}}));
const saved = snapshotClothDesign(data,scene);
assert(savedClothDesign(saved)?.scene);
data.logo.x = 200; new Float32Array(scene.bin)[0] = 999; scene.meta.meshes[0].name = 'different';
assert.equal(saved.data.logo.x,1);
assert.equal(new Float32Array(saved.scene.bin)[0],1);
assert.equal(saved.scene.meta.meshes[0].name,'front');
const clone = structuredClone(saved);
assert(isClothScene(clone.scene));
assert.deepEqual(clone.data.tokens,{color:'navy'});
assert.equal(snapshotClothDesign({...data,completed:0},scene),undefined);
assert.equal(savedClothDesign({data:{...data,back:null},scene}),null);
assert.equal(savedClothDesign({data:saved.data,scene:{bin:{}}}).scene,undefined);
setClothScene(clone.scene,clone.data.text);
assert.equal(getClothScene('navy tee'),clone.scene);
assert.equal(getClothScene('other design'),undefined);
setClothScene(null); assert.equal(getClothScene('navy tee'),undefined);
console.log('PASS saved 3D binary/mesh, captures, tokens and logo are independent snapshots; corrupt/unfinished payloads fail closed; scene cache cannot cross designs.');
