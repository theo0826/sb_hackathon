import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {loadTS} from './helpers/load-ts.mjs';
const domain=await loadTS('lib/design.ts');
const fixture=JSON.parse(await fs.readFile('tests/fixtures/team-design.json','utf8'));
const legacy={...fixture,fabric:{pattern:'stripes'},placements:[...fixture.placements,{...fixture.placements[1],id:'back-number',content:'text',text:'10'}]};
const plain=domain.simpleDesign({...legacy,garment:'hoodie',fabricImage:'/api/assets/11111111-1111-4111-8111-111111111111'});
assert.equal(plain.garment,'tee');assert.equal(plain.fabric,undefined);assert.equal(plain.fabricImage,undefined);assert.equal(plain.placements.length,2);assert(plain.placements.every(p=>p.content==='artwork'));
assert.equal(legacy.fabric.pattern,'stripes','Existing stored data is not mutated');
assert.deepEqual(domain.GARMENTS.map(g=>g.id),['tee']);assert(domain.isDesign(plain));
const asset='/api/assets/11111111-1111-4111-8111-111111111111';
const edited=domain.mockDesign('업로드 이미지를 왼쪽 가슴과 등판에 넣어줘',{...plain,image:asset});
assert.equal(edited.image,asset);assert.deepEqual(edited.placements.map(p=>p.side),['front','back']);assert.equal(edited.placements[0].widthCm,8);
const unsupported=domain.mockDesign('과잠 후드 줄무늬 빨간 소매',legacy);
assert.equal(unsupported.garment,'tee');assert.equal(unsupported.fabric,undefined);
const changed=domain.mockDesign('검정 반팔 왼쪽 가슴에 로고를 작게',domain.DEFAULT_DESIGN);
assert.equal(changed.color,'#262b34');assert.equal(changed.placements[0].x,302);assert.equal(changed.placements[0].widthCm,8);
console.log('PASS plain tee/logo-only contract, legacy draft normalization, no fabric/extra garments, front/back original image reuse and chest placement');
