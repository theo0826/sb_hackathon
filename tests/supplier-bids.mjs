import assert from 'node:assert/strict';
import { loadTS } from './helpers/load-ts.mjs';
const { DEFAULT_DESIGN } = await loadTS('lib/design.ts');
const { DEFAULT_ORDER } = await loadTS('lib/quote.ts');
const { EMPTY_DETAILS, estimate } = await loadTS('lib/order-workflow.ts');
const { getSupplier, SUPPLIERS } = await loadTS('lib/suppliers.ts');
const { matchingOffers, recommendedOffer, sortedOffers, productionOrder, bidRequestKey, readBidRequest, resetSupplierBids, BID_STORAGE_KEY } = await loadTS('lib/supplier-bids.ts');
const order = { ...DEFAULT_ORDER, group:'견적 검증', contactEmail:'qa@example.com', desiredDeliveryDate:'2099-12-20' };
const offers = matchingOffers(DEFAULT_DESIGN, order);
assert.deepEqual(offers.map(({supplier,price})=>[supplier.id,price.unit,price.total]), [['jangwi',4500,112500],['jeongneung',5000,125000],['seokgwan',5500,137500]]);
assert.equal(recommendedOffer(offers).supplier.id,'jangwi');
assert.deepEqual(sortedOffers(offers,'delivery').map(o=>o.supplier.id),['jeongneung','jangwi','seokgwan']);
assert.deepEqual(sortedOffers([...offers].reverse(),'price').map(o=>o.price.total),[112500,125000,137500]);
assert.deepEqual(matchingOffers(DEFAULT_DESIGN,{...order,sizes:{S:15,M:0,L:0,XL:0}}).map(o=>o.supplier.id),['jangwi','seokgwan']);
assert.equal(matchingOffers(DEFAULT_DESIGN,{...order,sizes:{S:5,M:0,L:0,XL:0}}).length,0);
assert.deepEqual(matchingOffers(DEFAULT_DESIGN,{...order,method:'자수'}).map(o=>o.supplier.id),['jeongneung']);
assert.equal(matchingOffers(DEFAULT_DESIGN,{...order,method:'지원하지 않는 방식'}).length,0);
assert.equal(matchingOffers(DEFAULT_DESIGN,{...order,printWidthCm:31}).length,0);
assert.equal(matchingOffers(DEFAULT_DESIGN,{...order,printHeightCm:41}).length,0);
assert.deepEqual(matchingOffers(DEFAULT_DESIGN,order,'2099-12-12').map(o=>o.supplier.id),['jeongneung'],'Use conservative upper production days for a deadline');
assert.equal(matchingOffers(DEFAULT_DESIGN,order,'2099-12-14').length,0);
const largeDesign={...DEFAULT_DESIGN,logoPlacement:{...DEFAULT_DESIGN.logoPlacement,width:32}};
assert.equal(matchingOffers(largeDesign,productionOrder(largeDesign,order)).length,0,'Logo width is part of print limits');
const cloth={text:'scene-A',category:{label:'반팔'},tokens:{},logo:null,front:'old capture',updatedAt:1};
const key=bidRequestKey(DEFAULT_DESIGN,order,EMPTY_DETAILS,cloth);
assert.equal(key,bidRequestKey(DEFAULT_DESIGN,order,EMPTY_DETAILS,{...cloth,front:'recaptured image',updatedAt:2}),'A recapture does not start another request');
assert.notEqual(key,bidRequestKey(DEFAULT_DESIGN,{...order,desiredDeliveryDate:'2099-12-21'},EMPTY_DETAILS,cloth));
assert.notEqual(key,bidRequestKey(DEFAULT_DESIGN,order,{...EMPTY_DETAILS,delivery:'pickup'},cloth));
assert.notEqual(key,bidRequestKey(DEFAULT_DESIGN,order,EMPTY_DETAILS,{...cloth,text:'scene-B'}));
const storage=new Map();
globalThis.sessionStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const original=readBidRequest(key,1000);
assert.deepEqual(original,{key,startedAt:1000,comparing:false,selectedId:null,sort:'recommended'});
storage.set(BID_STORAGE_KEY,JSON.stringify({...original,comparing:true,selectedId:'jeongneung',sort:'delivery'}));
assert.equal(readBidRequest(key,7000).selectedId,'jeongneung','Reload retains selection');
assert.equal(readBidRequest(key+'changed',7000).startedAt,7000,'Changed order starts a new request');
storage.set(BID_STORAGE_KEY,'broken JSON');assert.equal(readBidRequest(key,8000).startedAt,8000);
storage.set(BID_STORAGE_KEY,JSON.stringify({...original,startedAt:9000}));assert.equal(readBidRequest(key,8000).startedAt,8000,'Reject a future start time');
resetSupplierBids();assert.equal(storage.size,0);
for(const supplier of SUPPLIERS)assert.equal(getSupplier(supplier.id).name,supplier.name,'Older saved supplier IDs remain readable');
for(const offer of offers)assert(getSupplier(offer.supplier.id));
assert.equal(estimate(getSupplier('jeongneung'),{...order,method:'자수'}).unit,8500);
console.log('PASS supplier eligibility, deadline/minimum/method/print limits, exact Figma prices, ranking, request restoration/reset, and older saved supplier IDs.');

const { supplierOfferIssues } = await loadTS('lib/supplier-bids.ts');
assert(supplierOfferIssues(DEFAULT_DESIGN, {...order, desiredDeliveryDate:'2099-12-14'}, getSupplier('jangwi'), '2099-12-12').some(issue => issue.includes('2099-12-22')));
assert(supplierOfferIssues(DEFAULT_DESIGN, {...order, sizes:{S:1,M:0,L:0,XL:0}}, getSupplier('jangwi')).some(issue => issue.includes('10벌')));
